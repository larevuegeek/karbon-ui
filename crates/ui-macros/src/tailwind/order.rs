pub(super) fn property_rank(name: &str) -> usize {
    PROPERTY_ORDER
        .iter()
        .position(|p| *p == name)
        .unwrap_or_else(|| {
            if name.starts_with("--tw-") {
                // Variables propres à une famille : avec la propriété qu'elles composent.
                PROPERTY_ORDER.len()
            } else {
                PROPERTY_ORDER.len() + 1
            }
        })
}
