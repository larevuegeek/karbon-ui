//! Sous-arbres mémorisés, comme `Html.Lazy` d'Elm ou `React.memo` : une vue reconstruite
//! à chaque message (horloge de lecture, saisie…) ne refait pas ce qui ne dépend que d'une
//! clé inchangée. Le runtime remet à sa place le sous-arbre de la vue précédente, avec
//! ses styles résolus, ses mesures et son placement.
use super::Element;
use crate::ui::core::hash::FastMap;
use crate::ui::element::ElementId;
use std::cell::RefCell;
use std::hash::{Hash, Hasher};

thread_local! {
    /// Clés des sous-arbres mémorisés de la vue précédente, le temps d'un appel à `view`.
    static PREVIOUS: RefCell<Option<FastMap<ElementId, u64>>> = const { RefCell::new(None) };
}

/// Fingerprint of a memo key: any value whose `Hash` covers everything the subtree reads.
pub fn memo_key<T: Hash + ?Sized>(value: &T) -> u64 {
    let mut hasher = std::hash::DefaultHasher::new();
    value.hash(&mut hasher);
    hasher.finish()
}

/// `true` while a view is being built and the previous view had the subtree `id` with
/// the same key: [`lazy`] then returns a placeholder that the runtime replaces with
/// that subtree.
pub fn memo_reusable(id: ElementId, key: u64) -> bool {
    PREVIOUS.with(|p| {
        p.borrow()
            .as_ref()
            .is_some_and(|table| table.get(&id) == Some(&key))
    })
}

/// Placeholder for a subtree reused from the previous view (code generated by the
/// templates' `memo={…}` attribute).
#[doc(hidden)]
pub fn memo_placeholder(id: ElementId, key: u64) -> Element {
    Element::memo_placeholder(id, key)
}

/// Builds the element `id` with `build`, unless the previous view built it with the same
/// `key`: the runtime then reuses that subtree as it was (styles, measures, placement),
/// without calling `build`. `key` must cover everything the subtree reads; the element
/// returned by `build` must have the identifier `id`.
///
/// ```
/// use karbon_ui::ui::{view::{lazy, row, text}, element::Element};
///
/// fn track_row(id: u64, title: &str, playing: bool) -> Element {
///     lazy(id, &(title, playing), || row(id, [text(id + 1, title)]))
/// }
/// # let _ = track_row(1, "Titre", false);
/// ```
pub fn lazy<K: Hash + ?Sized>(
    id: impl Into<ElementId>,
    key: &K,
    build: impl FnOnce() -> Element,
) -> Element {
    let id = id.into();
    let key = memo_key(key);
    if memo_reusable(id, key) {
        return memo_placeholder(id, key);
    }
    build().memo(key)
}

/// Clés des sous-arbres mémorisés de `root`.
pub(crate) fn previous_keys(root: Option<&Element>) -> FastMap<ElementId, u64> {
    fn walk(node: &Element, table: &mut FastMap<ElementId, u64>) {
        if let Some(memo) = node.memo.as_deref() {
            table.insert(node.id, memo.key);
        }
        for child in &node.children {
            walk(child, table);
        }
    }
    let mut table = FastMap::default();
    if let Some(root) = root {
        walk(root, &mut table);
    }
    table
}

/// Construit la vue avec les clés de la vue précédente (`None` : rien n'est repris).
pub(crate) fn with_previous<R>(
    keys: Option<FastMap<ElementId, u64>>,
    view: impl FnOnce() -> R,
) -> R {
    struct Reset;
    impl Drop for Reset {
        fn drop(&mut self) {
            PREVIOUS.with(|p| *p.borrow_mut() = None);
        }
    }
    PREVIOUS.with(|p| *p.borrow_mut() = keys);
    let _reset = Reset;
    view()
}

/// Remplace les éléments vides posés par la vue (`memo_placeholder`) par les sous-arbres
/// de la vue précédente `old`, qui y laisse des éléments vides.
pub(crate) fn transplant(new: &mut Element, old: Option<&mut Element>) {
    fn wanted(node: &Element, ids: &mut FastMap<ElementId, ()>) {
        if node.memo.as_deref().is_some_and(|m| m.placeholder) {
            ids.insert(node.id, ());
            return;
        }
        for child in &node.children {
            wanted(child, ids);
        }
    }
    fn take(
        node: &mut Element,
        ids: &FastMap<ElementId, ()>,
        out: &mut FastMap<ElementId, Element>,
    ) {
        for child in &mut node.children {
            if ids.contains_key(&child.id) && child.memo.as_deref().is_some_and(|m| !m.placeholder)
            {
                let id = child.id;
                let empty = Element::memo_placeholder(id, 0);
                out.insert(id, std::mem::replace(child, empty));
            } else {
                take(child, ids, out);
            }
        }
    }
    fn give(node: &mut Element, taken: &mut FastMap<ElementId, Element>) {
        for child in &mut node.children {
            if child.memo.as_deref().is_some_and(|m| m.placeholder) {
                if let Some(mut subtree) = taken.remove(&child.id) {
                    if let Some(memo) = subtree.memo.as_deref_mut() {
                        memo.transplanted = true;
                    }
                    *child = subtree;
                }
            } else {
                give(child, taken);
            }
        }
    }
    let Some(old) = old else {
        return;
    };
    let mut ids = FastMap::default();
    wanted(new, &mut ids);
    if ids.is_empty() {
        return;
    }
    let mut taken = FastMap::default();
    take(old, &ids, &mut taken);
    give(new, &mut taken);
}
