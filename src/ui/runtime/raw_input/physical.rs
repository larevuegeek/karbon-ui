//! La place d'une touche sur le clavier, quelle que soit la disposition : ce que les jeux
//! et les caméras libres lient (ZQSD sur un AZERTY, WASD sur un QWERTY : les mêmes
//! touches). Les noms sont ceux des codes physiques du web (`KeyboardEvent.code`).

